/////Import CPU/GPU/Brightness/Volume data from host computer/////



#ifdef RAW_ENABLE
void raw_hid_receive(uint8_t *data, uint8_t length) {
    // Expected packet format:
    // data[0] = cpu
    // data[1] = gpu
    // data[2] = volume
    // data[3] = brightness

    if (length < 4) return;

    raw_cpu_usage = data[0];
    raw_gpu_usage = data[1];
    pc_vol        = data[2];
    pc_bright     = data[3];

    // Clamp values (just in case)
    if (raw_cpu_usage > 100) raw_cpu_usage = 100;
    if (raw_gpu_usage > 100) raw_gpu_usage = 100;
    if (pc_vol > 100) pc_vol = 100;
    if (pc_bright > 100) pc_bright = 100;
    if (raw_cpu_usage < 0) raw_cpu_usage = 0;
    if (raw_gpu_usage < 0) raw_gpu_usage = 0;
    if (pc_vol < 0) pc_vol = 0;
    if (pc_bright < 0) pc_bright = 0;
}
#endif
// Encoder volume/brightness meter

static void apply_rgb_effect(void) {

    uint8_t leds_on_vol = ((uint16_t)pc_vol * METER_LED_COUNT) / 100;
    uint8_t leds_on_bright = ((uint16_t)pc_bright * METER_LED_COUNT) / 100;
    uint8_t leds_on;


    if (enc_recently_used && timer_elapsed(enc_indicator_timer) < ENC_INDICATOR_TIMEOUT) {

        rgblight_enable_noeeprom();
        rgblight_mode_noeeprom(RGBLIGHT_MODE_STATIC_LIGHT);


        for (uint8_t i = 0; i < METER_LED_COUNT; i++) {
            rgblight_setrgb_at(0, 0, 0, i);
        }


        if (enc_mod) {
            leds_on = leds_on_bright;
        } else {
            leds_on = leds_on_vol;
        }


        for (uint8_t i = 0; i < leds_on; i++) {

            if (enc_mod) {
                rgblight_setrgb_at(255, 180, 0, i);
            } else {
                rgblight_setrgb_at(0, 120, 255, i);
            }
        }


    } else {

        switch (rgb_effect_mode) {


            case 0:

                rgblight_enable_noeeprom();
                rgblight_mode_noeeprom(RGBLIGHT_MODE_STATIC_LIGHT);

                for (uint8_t i = 8; i < RGB_COUNT; i++) {
                    rgblight_setrgb_at(0, 180, 150, i);
                }

                break;



            case 1:

                rgblight_enable_noeeprom();
                rgblight_mode_noeeprom(1);
                rgblight_setrgb(255,255,255);

                break;



            case 2:

                rgblight_enable_noeeprom();
                rgblight_mode_noeeprom(5);  

                break;



            case 3:

                rgblight_enable_noeeprom();
                rgblight_mode_noeeprom(RGBLIGHT_MODE_STATIC_LIGHT);


                for (uint8_t i = 8; i < RGB_COUNT; i++) {
                    rgblight_setrgb_at(0,0,0,i);
                }


                rgblight_setrgb_at(180,0,255,8);
                rgblight_setrgb_at(255,255,255,9);
                rgblight_setrgb_at(0,80,255,10);

                break;



            case 4:

                rgblight_disable_noeeprom();

                break;
        }
    }
}

// Automatically return from meter mode after timeout
void housekeeping_task_user(void) {

    if (enc_recently_used && timer_elapsed(enc_indicator_timer) > ENC_INDICATOR_TIMEOUT) {

        enc_recently_used = false;

        #ifdef RGBLIGHT_ENABLE
            apply_rgb_effect();
        #endif
    }
}



void keyboard_post_init_user(void) {
    apply_rgb_effect();
}



layer_state_t layer_state_set_user(layer_state_t state) {

    // Prevent layer changes overwriting encoder meter
    if (!enc_recently_used) {
        apply_rgb_effect();
    }

    return state;
}



///// Key handling code /////



bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {

        case PROF_NEXT:
            if (record->event.pressed) {
                layer_move((get_highest_layer(layer_state) + 1) % 5);
            }
            return false;

        case PROF_PREV:
            if (record->event.pressed) {
                layer_move((get_highest_layer(layer_state) + 4) % 5);
            }
            return false;

        case ENC_MOD:
            enc_mod = record->event.pressed;
            return false;

        case SCR_LEFT:
            if (record->event.pressed) {
                tap_code16(C(G(KC_LEFT)));
            }
            return false;

        case SCR_RIGHT:
            if (record->event.pressed) {
                tap_code16(C(G(KC_RIGHT)));
            }
            return false;

        case HCK_RGB:
            if (record->event.pressed) {
                rgb_effect_mode = (rgb_effect_mode + 1) % 5;
                #ifdef RGBLIGHT_ENABLE
                    apply_rgb_effect();
                #endif
            }
            return false;

        case NVIDIA:
            if (record->event.pressed) {
                tap_code16(A(KC_Z));   // Alt+Z
            }
            return false;

        case REPLAY:
            if (record->event.pressed) {
                tap_code16(A(KC_F10)); // Alt+F10
            }
            return false;
    }
    return true;
}



